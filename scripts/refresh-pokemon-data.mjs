import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { transform } from 'esbuild';
import { pokedex } from '../src/data/pokedex.js';
import { moveGroups } from '../src/data/teamCapabilities.js';

const urls = {
  dex: 'https://play.pokemonshowdown.com/data/pokedex.json',
  learnsets: 'https://play.pokemonshowdown.com/data/learnsets.json',
  moves: 'https://play.pokemonshowdown.com/data/moves.json',
  types: 'https://raw.githubusercontent.com/smogon/pokemon-showdown/master/data/typechart.ts',
  license: 'https://raw.githubusercontent.com/smogon/pokemon-showdown/master/LICENSE',
};
const responses = await Promise.all(Object.entries(urls).map(async ([key, url]) => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return [key, await response.text()];
}));
const raw = Object.fromEntries(responses);
const dex = JSON.parse(raw.dex);
const learnsets = JSON.parse(raw.learnsets);
const moves = JSON.parse(raw.moves);
const { code } = await transform(raw.types, { loader: 'ts', format: 'esm' });
const { TypeChart } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const toID = name => name.toLowerCase().replace(/[^a-z0-9]/g, '');
const wantedMoves = new Set(Object.values(moveGroups).flat());
const sourceSpecies = Object.entries(dex).filter(([, species]) => !species.forme && !species.baseSpecies);
const rosterNumbers = new Set(Object.values(pokedex));
const catalog = {};

for (const [name, number] of Object.entries(pokedex)) {
  const match = sourceSpecies.find(([, species]) => species.num === number);
  if (!match) throw new Error(`Missing species ${name} (${number})`);
  const [id, species] = match;
  const learned = new Set();
  let current = id;
  const visited = new Set();
  while (current && !visited.has(current)) {
    visited.add(current);
    for (const move of Object.keys(learnsets[current]?.learnset || {})) {
      if (wantedMoves.has(move)) learned.add(move);
    }
    current = dex[current]?.prevo ? toID(dex[current].prevo) : null;
  }
  const s = species.baseStats;
  catalog[name] = {
    id: number,
    types: species.types.map(type => type.toLowerCase()),
    stats: { hp: s.hp, attack: s.atk, defense: s.def, spAtk: s.spa, spDef: s.spd, speed: s.spe },
    abilities: [...new Set(Object.values(species.abilities))],
    terminalInRoster: !(species.evos || []).some(evo => rosterNumbers.has(dex[toID(evo)]?.num)),
    legendary: (species.tags || []).some(tag => /legendary|mythical/i.test(tag)),
    moves: [...learned].sort(),
  };
}
const typeNames = Object.keys(TypeChart).filter(type => type !== 'stellar');
const typeChart = Object.fromEntries(typeNames.map(attack => [attack,
  Object.fromEntries(typeNames.map(defense => {
    const key = attack[0].toUpperCase() + attack.slice(1);
    return [defense, [1, 2, 0.5, 0][TypeChart[defense].damageTaken[key] ?? 0]];
  })),
]));
const moveNames = Object.fromEntries([...wantedMoves].map(id => [id, moves[id]?.name || id]));
const metadata = {
  retrievedAt: new Date().toISOString(),
  sources: urls,
  sha256: Object.fromEntries(responses.map(([key, body]) => [key, createHash('sha256').update(body).digest('hex')])),
  scope: 'Modern base stats/types/abilities; historical move access including pre-evolutions. Not format legality validation.',
};
const output = `// Generated by scripts/refresh-pokemon-data.mjs. See doc/team-builder/handoff.md.\n` +
  `export const pokemonCatalog = {\n${Object.entries(catalog).map(([name, data]) => `  ${JSON.stringify(name)}: ${JSON.stringify(data)},`).join('\n')}\n};\n` +
  `export const typeChart = ${JSON.stringify(typeChart, null, 2)};\n` +
  `export const moveNames = ${JSON.stringify(moveNames, null, 2)};\n` +
  `export const catalogMetadata = ${JSON.stringify(metadata, null, 2)};\n`;
await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/data/pokemonCatalog.js', import.meta.url), output);
await mkdir(new URL('../doc/team-builder/', import.meta.url), { recursive: true });
await writeFile(new URL('../doc/team-builder/pokemon-showdown-LICENSE.txt', import.meta.url), raw.license);
await mkdir(new URL('../public/licenses/', import.meta.url), { recursive: true });
await writeFile(new URL('../public/licenses/pokemon-showdown.txt', import.meta.url), raw.license);
console.log(`Saved ${Object.keys(catalog).length} Pokémon, ${typeNames.length} types, and ${wantedMoves.size} capability moves.`);
